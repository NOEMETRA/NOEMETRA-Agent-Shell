"""Claims, evidence records, Red operation plan, and Blue investigation model contracts."""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class VerdictType(str, Enum):
    CONFIRMED_ATTACK = "CONFIRMED_ATTACK"
    EXPLOITABLE_CHAIN = "EXPLOITABLE_CHAIN"
    FALSE_POSITIVE_BENIGN = "FALSE_POSITIVE_BENIGN"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"


class EvidenceRecord(BaseModel):
    """Immutable verbatim record extracted from logs, code, config, or HTTP traces."""

    evidence_id: str
    source_type: Literal["log", "code", "config", "http"] = "log"
    line_or_seq: int
    timestamp: Optional[str] = None
    raw_content: str
    entities: Dict[str, List[str]] = Field(default_factory=dict)
    is_benign_baseline: bool = False


class ArtifactIngestionResult(BaseModel):
    """Normalized dataset produced deterministically by CyberObserver."""

    case_id: str
    title: str
    source_kind: str = "auto"
    sha256: str
    total_records: int
    evidences: List[EvidenceRecord] = Field(default_factory=list)
    summary_stats: Dict[str, Any] = Field(default_factory=dict)


class MitreStep(BaseModel):
    """Single step in a multi-hop MITRE ATT&CK kill-chain."""

    tactic: str
    technique_id: str
    technique_name: str
    description: str
    evidence_ids: List[str] = Field(default_factory=list)
    reachability_proof: str = ""
    claim_id: str = ""
    observed_fact: str = ""
    proposed_interpretation: str = ""
    missing_conditions: List[str] = Field(default_factory=list)
    confirming_or_refuting_proof: str = ""
    status: Literal["supported", "open", "refuted"] = "open"


class AnalyticalClaim(BaseModel):
    """Structured claim separating verbatim observed facts from hypotheses and missing proof."""

    claim_id: str
    step_index: int = 0
    tactic: str = ""
    technique_id: str = ""
    observed_fact: str
    evidence_ids: List[str] = Field(default_factory=list)
    subject_entities: Dict[str, List[str]] = Field(default_factory=dict)
    proposed_interpretation: str
    missing_conditions: List[str] = Field(default_factory=list)
    confirming_or_refuting_proof: str
    status: Literal["supported", "open", "refuted"] = "open"
    priority: Literal["critical", "high", "medium", "low"] = "medium"
    priority_rationale: str = ""


class RedProbe(BaseModel):
    """Controlled safe-audit operation verifying exploitability or exposure without damage."""

    probe_id: str
    title: str
    target_surface: str
    method_or_vector: str
    payload_or_command: str
    expected_ioc: str
    safety_level: str = "safe-audit"


class SimulatedAttackEvent(BaseModel):
    """Synthetic telemetry record generated by Red Operator for Purple Replay validation."""

    event_id: str
    variant: Literal["baseline_attack", "evasion_variant"] = "baseline_attack"
    log_line: str
    fields: Dict[str, Any] = Field(default_factory=dict)
    mitre_technique_id: str = ""
    claim_id: str = ""


class RedOperationPlan(BaseModel):
    """Offensive kill-chain, reachability analysis, safe probes, and evasion simulation."""

    primary_hypothesis: str
    confidence: float = Field(ge=0.0, le=1.0)
    kill_chain: List[MitreStep] = Field(default_factory=list)
    claims: List[AnalyticalClaim] = Field(default_factory=list)
    blind_spots: List[str] = Field(default_factory=list)
    probes: List[RedProbe] = Field(default_factory=list)
    simulated_events: List[SimulatedAttackEvent] = Field(default_factory=list)
    cited_evidence_ids: List[str] = Field(default_factory=list)
    model_used: str = "deterministic"


class ContradictionItem(BaseModel):
    """Adversarial finding challenging or contextualizing the primary threat hypothesis."""

    claim_challenged: str
    target_claim_id: Optional[str] = None
    target_evidence_ids: List[str] = Field(default_factory=list)
    contradicting_evidence_ids: List[str] = Field(default_factory=list)
    explanation: str
    impact_on_hypothesis: Literal["refutes", "weakens", "contextualizes"] = "weakens"
    entity_coherent: bool = True


class SigmaRuleSpec(BaseModel):
    """Structured Sigma rule evaluated deterministically during Purple Replay."""

    title: str
    id: str
    status: str = "experimental"
    description: str
    logsource: Dict[str, str] = Field(default_factory=dict)
    detection_keywords: List[str] = Field(default_factory=list)
    detection_fields: Dict[str, List[str]] = Field(default_factory=dict)
    exclude_fields: Dict[str, List[str]] = Field(default_factory=dict)
    level: str = "high"
    yaml_text: str = ""


class YaraRuleSpec(BaseModel):
    """Structured YARA-style pattern rule evaluated during Purple Replay."""

    rule_name: str
    description: str
    strings: List[str] = Field(default_factory=list)
    condition: str = "any of them"
    raw_rule: str = ""


class BlueInvestigationReport(BaseModel):
    """Defensive investigation: contradictions, competing hypothesis, Sigma/YARA, and patch."""

    competing_hypothesis: str
    confidence: float = Field(ge=0.0, le=1.0)
    contradictions: List[ContradictionItem] = Field(default_factory=list)
    sigma_rule: SigmaRuleSpec
    yara_rule: YaraRuleSpec
    remediation_patch: str
    hardening_steps: List[str] = Field(default_factory=list)
    cited_evidence_ids: List[str] = Field(default_factory=list)
    model_used: str = "deterministic"
